const I18n = {
  lang: 'en',

  t(key) {
    const pack = I18N_STRINGS[I18n.lang] || I18N_STRINGS.en;
    return pack[key] || I18N_STRINGS.en[key] || key;
  },

  ratingText(rating) {
    return I18n.t('rating' + rating);
  },

  apply() {
    document.documentElement.lang = I18n.lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const text = key ? I18n.t(key) : '';
      if (key && text && text !== key) el.textContent = text;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const key = el.getAttribute('data-i18n-aria');
      if (key) el.setAttribute('aria-label', I18n.t(key));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', I18n.t(key));
    });
    const popular = document.getElementById('langGroupPopular');
    const more = document.getElementById('langGroupMore');
    if (popular) popular.label = I18n.t('popularGroup');
    if (more) more.label = I18n.t('moreGroup');
  },
};
